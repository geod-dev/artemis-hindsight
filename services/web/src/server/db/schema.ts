import type { UIMessage } from "ai";
import {
  boolean,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  text,
  timestamp,
  uuid,
  type AnyPgColumn,
} from "drizzle-orm/pg-core";
import type { TemporaryMode } from "../../lib/temporary-chat";

// Users, their conversations and their messages. Messages store the AI SDK UIMessage parts as JSON,
// so every step (text, reasoning, tool calls and their results) is kept as it streamed.

export type UserStatus = "active" | "archived";

/**
 * A family member. The username is unique, lowercase and never changes: it also names the user's Hindsight
 * memory bank and their workspace folder (/workspace/<username>).
 *
 * The memory columns track what is still outside Hindsight: at most one conversation is active per user, and its
 * unsaved messages are flushed to memory when another conversation receives a message or after an hour of silence.
 */
export const users = pgTable("users", {
  id: uuid("id").primaryKey().defaultRandom(),
  username: text("username").notNull().unique(),
  passwordHash: text("password_hash").notNull(),
  status: text("status").$type<UserStatus>().notNull().default("active"),
  /** The one conversation that is still receiving messages. Null when every conversation has been flushed. */
  activeConversationId: uuid("active_conversation_id").references((): AnyPgColumn => conversations.id, {
    onDelete: "set null",
  }),
  /** When the active conversation last received a user message. */
  activeConversationAt: timestamp("active_conversation_at", { withTimezone: true }),
  /** The name shown in the app and given to the agent. Set by the admin; until it is set the user cannot use the app. */
  displayName: text("display_name"),
  /** One of the palette colors in lib/avatar-colors.ts. Null until the user picks one: the app derives one from the username. */
  avatarColor: text("avatar_color"),
  /** The GitHub repositories ("owner/repo") the user added as skill marketplaces, next to the built-in ones. */
  skillSources: jsonb("skill_sources").$type<string[]>().notNull().default([]),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

/**
 * A project: a folder of the user's workspace (<workspace>/<username>/projects/<id>) with a name, a color, an optional
 * icon and optional instructions for the agent. Conversations can belong to one project. Deleting the user deletes
 * their projects; deleting a project keeps its conversations, which then belong to no project.
 */
export const projects = pgTable(
  "projects",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    /** One of the palette colors in lib/avatar-colors.ts. */
    color: text("color").notNull(),
    /** The icon's file name in the project folder, e.g. "icon.png". Null when the project has no icon: its folder icon shows. */
    iconFile: text("icon_file"),
    /** Custom instructions for the agent, written by the user. Null when there are none. */
    description: text("description"),
    /** The place of the project in the user's list (the sidebar and the mobile drawer). Lower comes first. */
    position: integer("position").notNull().default(0),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [index("projects_user_name_idx").on(table.userId, table.name)],
);

export const conversations = pgTable(
  "conversations",
  {
    // Generated by the browser; it is also the AI SDK chat id sent with each request.
    id: uuid("id").primaryKey(),
    // The owner. Conversations are never shared between users.
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    // The project the conversation was created in. Null for a conversation outside any project, or once its project is deleted.
    projectId: uuid("project_id").references(() => projects.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    // True when a reply finished while no client was connected to receive it. Cleared when a client opens the
    // conversation or sends a message. Drives the unread badge in the conversation list.
    unread: boolean("unread").notNull().default(false),
    // Set when the owner archives the conversation: it leaves the list but keeps its messages. Null while it is listed.
    // Sending a message to an archived conversation clears it again.
    archivedAt: timestamp("archived_at", { withTimezone: true }),
    // Set for a temporary chat (see lib/temporary-chat.ts): never listed, never saved to memory, never named, and
    // deleted once no client has kept it alive for an hour. Null for every other conversation.
    temporary: text("temporary").$type<TemporaryMode>(),
    // When a client last showed this temporary chat (it calls /api/conversations/<id>/keepalive while it is open), or
    // when a turn last touched it. Null for other conversations.
    keptAliveAt: timestamp("kept_alive_at", { withTimezone: true }),
    // The last message of the branch the user is on: editing a message or regenerating a reply forks the conversation
    // (see messages.parentId), and this is the branch the clients open on. Null until the first message.
    activeLeafId: text("active_leaf_id"),
    // The last message of the branch that is in the user's Hindsight bank. The next flush appends what follows it when
    // the active branch continues it, and replaces the conversation's document with the active branch otherwise.
    // Null until the conversation is first saved.
    memorizedLeafId: text("memorized_leaf_id"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("conversations_user_updated_idx").on(table.userId, table.updatedAt),
    index("conversations_project_updated_idx").on(table.projectId, table.updatedAt),
  ],
);

export type MessageStatus = "streaming" | "complete" | "aborted" | "error";

/** One model step of a turn: a tool-calling step or the final answer step. */
export interface TurnStep {
  startedAt: number;
  /** When the step's first text arrived. The final answer's step is the last one with text. */
  firstTextAt?: number;
  endedAt?: number;
  finishReason?: string;
}

export interface TurnTiming {
  startedAt: number;
  endedAt?: number;
  steps: TurnStep[];
  /**
   * One entry per reasoning block of the turn, in stream order. The n-th reasoning part of the message is the
   * n-th entry here. Epoch milliseconds.
   */
  reasonings?: { startedAt: number; endedAt?: number }[];
}

/** What the model received for a user message: its text with the memory and metadata tags, and its files. */
export interface StoredModelInput {
  text: string;
  /** The files sent to the model as content (images and PDFs), without their data. */
  files: { filename?: string; mediaType: string }[];
}

/** A reasoning effort the user can choose. "auto" lets Jev pick one per reply. */
export type ReasoningEffortChoice = "auto" | "low" | "medium" | "high";

/**
 * The reasoning effort of one reply: what the user asked for, what the reply ran with, and who picked it. `decidedBy`
 * is "user" for a fixed effort, "jev" when Jev chose it, "fallback" when Auto could not ask Jev and used medium, and
 * "continued" when a continued reply keeps the effort of its first answer.
 */
export interface EffortDecision {
  requested: ReasoningEffortChoice;
  used: Exclude<ReasoningEffortChoice, "auto">;
  decidedBy: "user" | "jev" | "fallback" | "continued";
}

export interface StoredMessageMetadata {
  /** Facts recalled from Hindsight that were injected into this user message for the model. */
  memory?: {
    query: string;
    budget: string;
    /** "unavailable" when Hindsight could not be reached: `facts` is then empty and `reason` says why. */
    status?: "ok" | "unavailable";
    /** How long the recall call took, in milliseconds. Absent on messages stored before it was measured. */
    durationMs?: number;
    reason?: string;
    facts: { id?: string; text: string; type?: string }[];
  };
  /** The exact input the model read for this user message. Absent on messages stored before it was recorded. */
  modelInput?: StoredModelInput;
  model?: string;
  /** The reasoning effort the user message was sent with ("auto" included). Absent on messages stored before it was recorded. */
  reasoningEffort?: ReasoningEffortChoice;
  /** Assistant messages: the reasoning effort the reply ran with, and who chose it. Absent on older replies. */
  effort?: EffortDecision;
  /** The assistant turn's timing, measured by the server. Epoch milliseconds. */
  turnTiming?: TurnTiming;
  /** assistant-ui's composer quote, kept under the same key the runtime uses (metadata.custom). */
  custom?: { quote?: { text: string; messageId?: string } };
}

export const messages = pgTable(
  "messages",
  {
    id: text("id").primaryKey(),
    conversationId: uuid("conversation_id")
      .notNull()
      .references(() => conversations.id, { onDelete: "cascade" }),
    role: text("role").$type<"user" | "assistant" | "system">().notNull(),
    // The message this one follows. Null for a first message. Two messages with the same parent are branches: an edit is a
    // new user message beside the one it edits, a regenerated reply a new assistant message beside the old one.
    parentId: text("parent_id"),
    // Insertion order across the whole conversation, every branch included. Siblings are shown in this order.
    position: integer("position").notNull(),
    parts: jsonb("parts").$type<UIMessage["parts"]>().notNull(),
    metadata: jsonb("metadata").$type<StoredMessageMetadata>(),
    status: text("status").$type<MessageStatus>().notNull().default("complete"),
    /** When this message was retained in the user's Hindsight bank. Null while it has not been sent yet. */
    memorizedAt: timestamp("memorized_at", { withTimezone: true }),
    // When the user last had this message at the end of the branch they were on. At a fork, the clients open the
    // branch visited last.
    visitedAt: timestamp("visited_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("messages_conversation_position_idx").on(table.conversationId, table.position),
    index("messages_parent_idx").on(table.parentId),
  ],
);

/** What a model call served. */
export type ModelCallContext = "conversation" | "title" | "memory" | "image" | "effort";

/** What the call did: write a reply, a title or an image, or one of the memory's operations. */
export type ModelCallOperation = "generate" | "retain" | "recall" | "reflect" | "consolidate" | "refresh";

/**
 * Why the call ran.
 *  - `message_sent`: a reply to the user's message, and the memory recall it starts.
 *  - `conversation_created`: the name of a new conversation.
 *  - `tool_call`: a tool the agent called (an image, a reflect on the memory).
 *  - `conversation_inactive`: a conversation saved to memory once it is no longer the active one.
 *  - `recurrent_task`: a scheduled job (the daily consolidation and the refresh of the memory summaries).
 *  - `user_action`: a button the user pressed (rename from the conversation, name the untitled conversations).
 */
export type ModelCallCause =
  | "message_sent"
  | "conversation_created"
  | "tool_call"
  | "conversation_inactive"
  | "recurrent_task"
  | "user_action";

/** The kinds of tokens a call is billed for. Each one appears only when the call used it. */
export type ModelCallTokenKind =
  | "input"
  | "cache_read"
  | "cache_write"
  | "output"
  | "image_input"
  | "image_output";

/** The tokens of each kind the provider reported for a call, and what they cost (US dollars). */
export type ModelCallUsage = Partial<Record<ModelCallTokenKind, { tokens: number; cost: number }>>;

/**
 * Every model call made for a user, with what it cost, one row per request to a provider. Rows are written once and
 * never priced again: `cost_usd` is the price of the day the call ran. The tokens are the ones the provider reported
 * (Anthropic and OpenAI usage, Hindsight's request log), never estimates.
 *
 * The app writes its own calls as they end (replies, titles, images). Memory calls run inside Hindsight: a job copies
 * them from Hindsight's request log (server/usage/memory-calls.ts). `source_key` is the provider's id for the call, so a
 * call is never counted twice.
 *
 * `conversation_id` and `message_id` are not foreign keys: the cost of a conversation stays after it is deleted.
 */
export const modelCalls = pgTable(
  "model_calls",
  {
    id: uuid("id").primaryKey().defaultRandom(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    /** The provider's id for the call: "anthropic:msg_…", "openai:<uuid>", "hindsight:<request id>". */
    sourceKey: text("source_key").notNull().unique(),
    context: text("context").$type<ModelCallContext>().notNull(),
    operation: text("operation").$type<ModelCallOperation>().notNull(),
    cause: text("cause").$type<ModelCallCause>().notNull(),
    /** The model as the provider named it in its answer. */
    model: text("model").notNull(),
    usage: jsonb("usage").$type<ModelCallUsage>().notNull(),
    /** The sum of the usage costs. */
    costUsd: numeric("cost_usd", { precision: 14, scale: 8, mode: "number" }).notNull(),
    /** The conversation the call served: replies, titles, images, and the memory saves of a conversation. */
    conversationId: uuid("conversation_id"),
    /** The assistant message the call belongs to: each step of a reply, and an image made during it. */
    messageId: text("message_id"),
    /** When the call ran. */
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    index("model_calls_user_created_idx").on(table.userId, table.createdAt),
    index("model_calls_conversation_idx").on(table.conversationId),
  ],
);

/** One image result of a Brave image search, as the image groups in replies show it. */
export interface StoredImageResult {
  /** Brave's proxied thumbnail: always loads, about 500 px wide. */
  thumbnailUrl: string;
  /** The full image on its origin site. Some sites block hotlinking, so the thumbnail is the fallback. */
  imageUrl: string;
  /** The page the image comes from. */
  pageUrl: string | null;
  title: string;
  source: string;
  /** The image's size in pixels, when Brave gives it. Searches stored before these fields existed lack them. */
  width?: number;
  height?: number;
}

/**
 * The answer Brave gave for each image group query. A reply is shown again on every reload, so a query is searched
 * once and then read from here: the same reply keeps the same images, and Brave is not called again.
 */
export const imageSearches = pgTable("image_searches", {
  /** The query as the agent wrote it, with whitespace collapsed and lowercased. */
  query: text("query").primaryKey(),
  results: jsonb("results").$type<StoredImageResult[]>().notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

// Generates src/theme/tokens.ts from the web app's theme (services/web/src/app/globals.css), so the mobile app uses the
// same colour tokens with the same names. Run it after the web theme changes:
//   node scripts/sync-theme.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(path.resolve(mobileRoot, "../../services/web/src/app/globals.css"), "utf8");

function block(pattern, name) {
  const match = css.match(pattern);
  if (!match) throw new Error(`${name} block not found in globals.css`);
  return match[1];
}

// The light tokens are the :root / .light block; .dark overrides them. Only the colour tokens are kept.
const light = declarations(block(/:root,\s*\.light\s*\{([\s\S]*?)\}/, ":root/.light"));
const dark = declarations(block(/\.dark\s*\{([\s\S]*?)\}/, ".dark"));

function declarations(body) {
  const out = {};
  for (const match of body.matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)) {
    const [, name, value] = match;
    if (name.startsWith("radius") || name.startsWith("color-") || name.startsWith("shadow") || name.startsWith("font")) continue;
    out[name] = value.trim();
  }
  return out;
}

// Resolves var(--x) inside the same block (--primary is var(--foreground) in dark mode).
function resolve(tokens, value, depth = 0) {
  const reference = value.match(/^var\(--([a-z0-9-]+)\)$/);
  if (!reference || depth > 5) return value;
  const next = tokens[reference[1]];
  return next === undefined ? value : resolve(tokens, next, depth + 1);
}

// OKLCH to sRGB hex (or rgba for an alpha), with the standard OKLab matrices. Exact, no colour library.
function toColour(value) {
  if (value.startsWith("#")) return value;
  const match = value.match(/^oklch\(\s*([\d.]+)(%?)\s+([\d.]+)\s+([\d.]+)(?:\s*\/\s*([\d.]+)(%?))?\s*\)$/);
  if (!match) throw new Error(`unsupported colour: ${value}`);
  const [, l0, lPercent, c, h, alpha, alphaPercent] = match;
  const L = lPercent ? Number(l0) / 100 : Number(l0);
  const C = Number(c);
  const H = (Number(h) * Math.PI) / 180;
  const a = C * Math.cos(H);
  const b = C * Math.sin(H);
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3;
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3;
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3;
  const linear = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  const [r, g, bl] = linear.map((x) => {
    const clamped = Math.min(1, Math.max(0, x));
    const encoded = clamped <= 0.0031308 ? 12.92 * clamped : 1.055 * clamped ** (1 / 2.4) - 0.055;
    return Math.round(Math.min(1, Math.max(0, encoded)) * 255);
  });
  if (alpha === undefined) return "#" + [r, g, bl].map((x) => x.toString(16).padStart(2, "0")).join("");
  const opacity = alphaPercent ? Number(alpha) / 100 : Number(alpha);
  return `rgba(${r}, ${g}, ${bl}, ${opacity})`;
}

function convert(tokens) {
  const out = {};
  for (const name of Object.keys(tokens)) {
    out[name] = toColour(resolve(tokens, tokens[name]));
  }
  return out;
}

const body = (tokens) =>
  Object.entries(convert(tokens))
    .map(([name, value]) => `  "${name}": "${value}",`)
    .join("\n");

const output = `// GENERATED by scripts/sync-theme.mjs from services/web/src/app/globals.css. Do not edit by hand: change the web theme
// and run the script. The names are the web's token names (--background, --primary, ...).

export const lightTokens = {
${body(light)}
} as const;

export const darkTokens = {
${body(dark)}
} as const;

export type ThemeToken = keyof typeof lightTokens;
`;

writeFileSync(path.join(mobileRoot, "src/theme/tokens.ts"), output);
console.log(`wrote src/theme/tokens.ts: ${Object.keys(light).length} light, ${Object.keys(dark).length} dark tokens`);
